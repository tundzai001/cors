    function detectLanguage() {
        const preferences = Array.isArray(navigator.languages) && navigator.languages.length
            ? navigator.languages
            : [navigator.language || ''];
        const tags = preferences.map(preference => String(preference).replace(/_/g, '-').toLowerCase());
        if (tags.some(tag => tag.split('-').includes('vn'))) return 'vi';
        try {
            if (Intl.DateTimeFormat().resolvedOptions().timeZone === 'Asia/Ho_Chi_Minh') return 'vi';
        } catch (_) {}
        for (const tag of tags) {
            if (tag === 'vi' || tag.startsWith('vi-')) return 'vi';
            if (tag === 'en' || tag.startsWith('en-')) return 'en';
        }
        return 'en';
    }

    function skipTextNode(node) {
        return !node.nodeValue?.trim()
            || node.parentElement?.closest('script,style,textarea,pre,code,noscript,[data-no-translate]');
    }

    function translateTextNode(node) {
        if (skipTextNode(node)) return;
        const current = node.nodeValue;
        const previousOutput = TEXT_OUTPUTS.get(node);
        if (!TEXT_SOURCES.has(node) || current !== previousOutput) TEXT_SOURCES.set(node, current);
        const output = translateText(TEXT_SOURCES.get(node));
        TEXT_OUTPUTS.set(node, output);
        if (current !== output) node.nodeValue = output;
    }

    function translateAttribute(element, name) {
        const current = element.getAttribute(name);
        if (current == null) return;
        let sources = ATTRIBUTE_SOURCES.get(element);
        let outputs = ATTRIBUTE_OUTPUTS.get(element);
        if (!sources) {
            sources = new Map();
            ATTRIBUTE_SOURCES.set(element, sources);
        }
        if (!outputs) {
            outputs = new Map();
            ATTRIBUTE_OUTPUTS.set(element, outputs);
        }
        if (!sources.has(name) || current !== outputs.get(name)) sources.set(name, current);
        const output = translateText(sources.get(name));
        outputs.set(name, output);
        if (current !== output) element.setAttribute(name, output);
    }

    function apply(root = document.documentElement) {
        if (!root) return;
        if (root.nodeType === Node.TEXT_NODE) {
            translateTextNode(root);
            return;
        }
        const elements = root.nodeType === Node.ELEMENT_NODE ? [root, ...root.querySelectorAll('*')] : [];
        elements.forEach(element => ATTRIBUTE_NAMES.forEach(name => translateAttribute(element, name)));
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) translateTextNode(node);
    }

    function updateButton() {
        if (!languageButton) return;
        languageButton.setAttribute('aria-label', currentLanguage === 'en' ? 'Select language' : 'Chọn ngôn ngữ');
        languageButton.querySelectorAll('[data-language]').forEach(option => {
            const selected = option.dataset.language === currentLanguage;
            option.setAttribute('aria-pressed', String(selected));
            option.title = option.dataset.language === 'en' ? 'English' : 'Tiếng Việt';
            option.setAttribute('aria-label', option.title);
        });
    }

    function isVisible(element) {
        return Boolean(element && getComputedStyle(element).display !== 'none' && element.getClientRects().length);
    }

    function findLanguageHost() {
        const landingNavbar = document.querySelector('.landing-navbar');
        const landingActions = landingNavbar?.querySelector('.landing-nav-actions');
        if (isVisible(landingNavbar) && isVisible(landingActions)) {
            return { container: landingActions, before: landingActions.querySelector('.btn-login-nav') };
        }

        for (const navbar of document.querySelectorAll('nav.navbar')) {
            if (!isVisible(navbar)) continue;
            const accountButton = navbar.querySelector('#logout-btn, #login-btn');
            const container = accountButton?.parentElement || navbar.querySelector('.container-fluid > .d-flex.align-items-center');
            if (container) return { container, before: accountButton?.parentElement === container ? accountButton : null };
        }
        return null;
    }

    function placeLanguageButton() {
        if (!languageButton) return;
        const host = findLanguageHost();
        if (host) {
            if (languageButton.classList.contains('app-language-switcher-floating')) {
                languageButton.classList.remove('app-language-switcher-floating');
            }
            if (languageButton.parentElement !== host.container || (host.before && languageButton.nextElementSibling !== host.before)) {
                host.container.insertBefore(languageButton, host.before);
            }
            return;
        }
        if (!languageButton.classList.contains('app-language-switcher-floating')) {
            languageButton.classList.add('app-language-switcher-floating');
        }
        if (languageButton.parentElement !== document.body) document.body.appendChild(languageButton);
    }

    function scheduleLanguageButtonPlacement() {
        if (headerPlacementScheduled) return;
        headerPlacementScheduled = true;
        const place = () => {
            headerPlacementScheduled = false;
            placeLanguageButton();
        };
        if (window.requestAnimationFrame) window.requestAnimationFrame(place);
        else setTimeout(place, 0);
    }

