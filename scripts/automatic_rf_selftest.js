'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('cors_dashboard/src/js/dashboard-live.js','utf8');
const code = source.slice(source.indexOf('function getAutomaticRfAssessment('),source.indexOf('function getRfDiagnostic('));
const assess = vm.runInNewContext(`${code};getAutomaticRfAssessment;`);
const report = {source:'ubx_mon_rf',age_seconds:0,sample_count:4,warning_samples:2,critical_samples:0,episodes:1,
    coincident_cno_drops:1,quality_comparisons:3,current_severity:1};
const device = {timestamp:100,gnss_rf_monitor:report};
assert.match(assess(device,true,100).title,/kèm/);
assert.match(assess(device,false,100).title,/thiếu mẫu/);
assert.match(assess(device,true,146).title,/thiếu mẫu/);
assert.match(assess({...device,gnss_rf_monitor:{...report,current_severity:null}},true,100).title,/thiếu mẫu/);
assert.match(assess({...device,gnss_rf_monitor:{...report,sample_count:1}},true,100).title,/Đang thu mẫu/);
assert.equal(assess({},true,100).report,null);
assert.equal(assess({...device,gnss_rf_monitor:{...report,sample_count:NaN}},true,100).report,null);
assert.equal(assess({...device,gnss_rf_monitor:{...report,source:'untrusted'}},true,100).report,null);
assert.match(assess({...device,gnss_rf_monitor:{...report,source:'unicore_rf',coincident_cno_drops:0}},true,100).title,/cảnh báo RF/);
console.log('PASS: automatic Pi RF report, warm-up, UM, unknown/stale/offline and malformed reports');

const windowModel = vm.runInNewContext(`${code};getRfMonitorWindow;`);
const history = {...report,observed_seconds:120,samples:[[120,0,null],[90,1,-4],[0,2,-1]]};
let model=windowModel({...device,gnss_rf_monitor:history},true,100);
assert.equal(model.elapsed,120);assert.equal(model.samples.length,3);assert.equal(model.age,0);
model=windowModel({...device,gnss_rf_monitor:{...history,observed_seconds:900}},true,100);
assert.equal(model.elapsed,600);
model=windowModel({...device,gnss_rf_monitor:{...report,first_sample_at:10,last_sample_at:130}},true,100);
assert.equal(model.elapsed,120);assert.equal(model.samples.length,0,'old agents must not fabricate sample points');
model=windowModel({...device,gnss_rf_monitor:{...history,samples:[[0,5,null],[0,1,NaN],[-1,0,null],[0,0,null]]}},true,100);
assert.equal(model.samples.length,1);
model=windowModel({...device,gnss_rf_monitor:{...history,samples:[[590,1,null],[0,0,null]]}},true,120);
assert.equal(model.samples.length,1,'expired samples leave the timeline');
console.log('PASS: window progress, bounded rolling timeline, old agents and invalid/stale sample points');
